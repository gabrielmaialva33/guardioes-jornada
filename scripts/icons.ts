const data = JSON.parse(readFileSync('node_modules/@iconify-json/ph/icons.json', 'utf8')) as {
	icons: Record<string, { body: string }>;
};

const entries: string[] = [];
for (const [name, { ph, weights }] of Object.entries(ICONS)) {
	for (const weight of weights) {
		const key = weight === 'regular' ? ph : `${ph}-${weight}`;
		const body = data.icons[key]?.body;
		if (!body) throw new Error(`Phosphor icon not found: ${key}`);
		entries.push(`\t${JSON.stringify(`${name}:${weight}`)}: ${JSON.stringify(body)}`);
	}
}

const names = Object.keys(ICONS)
	.map((n) => JSON.stringify(n))
	.join(' | ');

writeFileSync(
	'src/lib/icons.generated.ts',
	`// Generated by scripts/icons.ts from Phosphor Icons (MIT). Do not edit by hand.\n\n` +
		`export type IconName = ${names};\n` +
		`export type IconWeight = 'regular' | 'bold' | 'fill' | 'duotone';\n\n` +
		`export const ICON_BODIES: Partial<Record<\`\${IconName}:\${IconWeight}\`, string>> = {\n${entries.join(',\n')}\n};\n\n` +
		`export const DEFAULT_WEIGHT: Record<IconName, IconWeight> = ${JSON.stringify(
			Object.fromEntries(Object.entries(ICONS).map(([n, { weights }]) => [n, weights[0]])),
			null,
			'\t'
		)};\n`
);

console.log(`icons.generated.ts: ${entries.length} icon variants`);
